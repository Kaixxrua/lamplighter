export const LOOK27 = {
  night: { lamp: LOOK17.lamp, amb: [0.0006, 0.0008, 0.0012], wb: -0.3 },
  // the morning: the lamps of the floors above the lighthouse's, and of the lighthouse's own a little
  morning: { lamp: 1.0, near: 0.45, amb: [0.0045, 0.0034, 0.0022], wb: 0.1 },
  // the lamps warm from the top down: the floors above the lighthouse's third at t0, each floor below
  // per s later, each over ramp s, down to the lighthouse's floor (the morning reaches no deeper: the
  // shaft below keeps the night's lamps and goes dark)
  wave: { t0: 2.0, per: 0.07, ramp: 1.4 },
  swell: [5.3, 6.0], // the lighthouse's floor comes up to the morning as the card goes
  warm: [2.0, 5.0], // the air and the grade
  ev: [0.6, 0.6], // over the act's grade: cold, warm
  beamW: [0.02, 0.0015], // the sheet's half-width (rad) turning, at rest
  rest: [1.6, 2.4], // when it settles
  after: { trail: 0.1, len: 0.04 }, // the glow it holds at rest behind it (intensity, rad to 1/e)
  haze: [2.0, 2.6], // the sheet in the air and the lens's flash go
  windows: [2.2, 3.2], // the tower's lit windows go out: the watch is over
  // the air's density (as s17–s19 at the cut): thickening as the card comes up, so the far galleries and
  // the depth behind it go dark
  fog: [[0, 0.009], [0.4, 0.009], [1.6, 0.028], [5, 0.04]],
  dust: 0.6,
  hot: [3.0, 0.45, 2.5], // the written ink's lime, its time to 1/e (s), the head's lime
  phos: 3.0, // the cut 08:00 and hour line, lime where the sheet lies
  env: 0.004, // the brass's sheen of the gallery's light
};
const TRAIL = 0.6; // the sheet's afterglow at full speed and…
const PERSIST = 0.35; // …its time to 1/e (s), as in s13–s14

export function lampAt(k, t) {
  const W = LOOK27.wave;
  if (k < FLOOR) return LOOK27.night.lamp;
  const t0 = W.t0 + W.per * Math.max(0, FLOOR + 3 - k);
  const up = smoothstep(t0, t0 + W.ramp, t);
  if (k > FLOOR) return lerp(LOOK27.night.lamp, LOOK27.morning.lamp, up);
  // the lighthouse's floor: a little with the wave, the rest of the way once the letter is written and
  // the card is going
  const near = lerp(LOOK27.night.lamp, LOOK27.morning.near, up);
  return lerp(near, LOOK27.morning.lamp, smoothstep(...LOOK27.swell, t));
}

export function sheetState(t) {
  const ang = sheetAngle(t);
  const w = omegaAt(t);
  const rest = smoothstep(...LOOK27.rest, t);
  const haze = 1 - smoothstep(...LOOK27.haze, t);
  return {
    angle: ang,
    lamp: 1,
    glow: haze,
    beam: 1,
    vol: 0.06 * haze,
    trail: lerp(TRAIL * (w / SWEEP.omega), LOOK27.after.trail, rest),
    trailLen: lerp(Math.max(0.05, w * PERSIST), LOOK27.after.len, rest),
    trailArc: ang - SWEEP.theta0,
    dot: 1,
    windows: 1 - smoothstep(...LOOK27.windows, t),
    fanUp: SWEEP.fan.up,
    fanDn: SWEEP.fan.dn,
    halo: 1,
    bounce: LOOK.bounce,
  };
}

// ---------------------------------------------------------------------------------------------- setup

export async function setup(ctx) {
  await loadFonts();
  const tl = await ctx.load.json('/film/timeline.json');
  const grade = tl.grades.act2;
  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(30, 16 / 9, 0.05, 1200);
  const K0 = FLOOR - 40;
  const K1 = FLOOR + 4;
  const lib = new Library({ floors: [K0, K1], near: 2, mid: 10, height: ctx.height });
  scene.add(lib.group);
  lib.setAll(() => ({ lit: 0, lime: 0, lamp: LOOK27.night.lamp }));
  const U = lib.uniforms;
  U.uFogD.value = 0.009;
  U.uFogCol.value.setRGB(0, 0, 0);
  U.uBeamCol.value.setRGB(...LOOK.beamCol);

  const lh = new Lighthouse({ uniforms: U, y0: Y0 });
  scene.add(lh.group);
  const dust = new Dust({ uniforms: U, count: LOOK.motes, box: 18, seed: 27 });
  scene.add(dust.points);

  // B's gate stands on this floor (s19, side 0); never in the picture
  const gb = new Builder();
  gb.setTransform(gateMatrix());
  buildGate(gb);
  scene.add(new THREE.Mesh(gb.geometry(), lib.material));

  // the dial: the plate at 8 o'clock and the other hours' ticks; the letter
  const db = new Builder();
  db.setTransform(new THREE.Matrix4().makeTranslation(0, Y0, 0));
  buildDial(db);
  scene.add(new THREE.Mesh(db.geometry(), lib.material));
  const colours = Object.fromEntries(RIVERS.map((R) => [R.name, R.col ?? LIME]));
  const paper = LOOK18.paper;
  const page = await pageCanvas({ paper, ink: paper.map((v) => v * 0.07), colours, repos: PASSED.slice(0, 2) });
  const L = letterMeshes({ U, y0: Y0, page, mark: await trayMark(), LIB_COMMON, paper });
  scene.add(L.sheet, L.top);
  L.uniforms.uRows.value.forEach((r, i) => {
    r.z = BELLS[i] + LINE.lag;
    r.w = LINE.dur;
  });
  L.uniforms.uHot.value.set(...LOOK27.hot);
  L.trayUniforms.uPhos.value = LOOK27.phos;
  L.trayUniforms.uEnv.value = LOOK27.env;

  // keep the cues honest: recompute them from the scene and the timeline
  {
    const r2 = (x) => +x.toFixed(2);
    const row = (id) => tl.shots.find((s) => s.id === id);
    const start = row('s27').start;
    const ping0 = row('s16').start; // the ping: a beat a second from s16's cut
    const pings = [];
    for (let g = ping0; g < start + STOP * 24; g += 24) if (g >= start) pings.push(r2((g - start) / 24));
    let stop = 0;
    while (stop < END && omegaAt(stop) > 1e-9) stop += 1 / 240;
    const at = (((sheetAngle(stop) % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI)) / ((30 * Math.PI) / 180);
    const rows = L.uniforms.uRows.value;
    const got = {
      pings,
      stop: r2(stop),
      hour: Math.abs(at - hourBearing(8) / ((30 * Math.PI) / 180)) < 1e-6 ? 8 : r2(at + 5),
      bells: rows.map((r) => r2(r.z - LINE.lag)),
      lines: rows.map((r) => [r2(r.z), r2(r.z + r.w)]),
      rows: PRINT_ROWS.length,
    };
    const off = (a, b) => (typeof a === 'number' ? !(Math.abs(a - b) <= 0.03) : Object.keys(a ?? {}).some((k) => off(a[k], b?.[k])));
    for (const k of Object.keys(got)) {
      if (off(got[k], CUES[k])) console.warn(`[s27] CUES.${k} is ${JSON.stringify(CUES[k])}, the scene gives ${JSON.stringify(got[k])}`);
    }
  }

  const cam = {};
  const pos = new THREE.Vector3();
  const tgt = new THREE.Vector3();
  const fp = new THREE.Vector3();
  const lantern = new THREE.Vector3(0, LAMP, 0);
  const letter = sheetCentre().add(new THREE.Vector3(0, Y0, 0));
  const amb = [new THREE.Color(...LOOK27.night.amb), new THREE.Color(...LOOK27.morning.amb)];
  const focusAt = (t) => focusDistance(camera, fp.lerpVectors(lantern, letter, smoothstep(0.8, 3.2, t)));
  const fstopAt = (t) => lerp(CAM.fstop[0], CAM.fstop[1], smoothstep(0.8, 3.2, t));
  return {
    scene,
    camera,
    clearColor: new THREE.Color(0, 0, 0),
    update(t) {
      camAt(t, cam);
      pos.set(0, Y0 + cam.y, cam.z);
      tgt.set(-Math.sin(cam.al), -Math.cos(cam.al), 0).add(pos);
      setLens(camera, cam.lens);
      aim(camera, pos, tgt);
      lib.update(camera);
      U.uTime.value = 100 + t;
      U.uFogD.value = curve(LOOK27.fog, t);
      for (let k = K0; k <= K1; k++) lib.setFloor(k, { lamp: lampAt(k, t) });
      U.uAmb.value.copy(amb[0]).lerp(amb[1], smoothstep(...LOOK27.warm, t));
      U.uBeamW.value = lerp(LOOK27.beamW[0], LOOK27.beamW[1], smoothstep(...LOOK27.rest, t));
      lh.set(sheetState(t));
      lh.update(camera);
      L.uniforms.uShot.value = t;
      dust.update(camera, 100 + t, { focus: focusAt(t), fstop: fstopAt(t), width: ctx.width, intensity: LOOK.dust * LOOK27.dust });
    },
    post(t) {
      const w = smoothstep(...LOOK27.warm, t);
      return {
        exposure: grade.exposure + lerp(LOOK27.ev[0], LOOK27.ev[1], w),
        whiteBalance: { temperature: lerp(LOOK27.night.wb, LOOK27.morning.wb, w) },
        dof: { focus: focusAt(t), fstop: fstopAt(t) },
      };
    },
  };
}

