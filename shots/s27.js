export const STOP = 2.0;
// the sheet's turn past T0 (rad): full speed (π/2 rad/s, as it has turned all night) at the cut, easing to
// rest at 90°, 8 o'clock, at STOP (speed and its slope continuous at the cut)
export const phiAt = (t) => {
  const x = clamp(t / STOP);
  return Math.PI * (x - x ** 3 + x ** 4 / 2);
};
export const omegaAt = (t) => {
  const x = clamp(t / STOP);
  return (Math.PI / STOP) * (1 - 3 * x * x + 2 * x ** 3);
};
export const sheetAngle = (t) => sweepAngle(T0) + phiAt(t);

