// a monotone C1 curve through keys (Fritsch–Carlson), flat at the ends
function curve(keys, t) {
  const n = keys.length;
  if (t <= keys[0][0]) return keys[0][1];
  if (t >= keys[n - 1][0]) return keys[n - 1][1];
  let i = 0;
  while (t > keys[i + 1][0]) i++;
  const d = (j) => (keys[j + 1][1] - keys[j][1]) / (keys[j + 1][0] - keys[j][0]);
  const m = (j) => {
    if (j === 0 || j === n - 1) return 0;
    const a = d(j - 1);
    const b = d(j);
    if (a * b <= 0) return 0;
    const h0 = keys[j][0] - keys[j - 1][0];
    const h1 = keys[j + 1][0] - keys[j][0];
    return (3 * (h0 + h1)) / ((2 * h1 + h0) / a + (h1 + 2 * h0) / b); // weighted harmonic mean
  };
  const [t0, v0] = keys[i];
  const [t1, v1] = keys[i + 1];
  const h = t1 - t0;
  const u = (t - t0) / h;
  const u2 = u * u;
  const u3 = u2 * u;
  return (2 * u3 - 3 * u2 + 1) * v0 + (u3 - 2 * u2 + u) * h * m(i) + (-2 * u3 + 3 * u2) * v1 + (u3 - u2) * h * m(i + 1);
}
export function camAt(t, out = {}) {
  out.y = curve(CAM.y, t);
  out.z = curve(CAM.z, t);
  const Y = CAM.y;
  const e = (Y[0][1] - out.y) / (Y[0][1] - Y[Y.length - 1][1]); // how far down
  out.lens = lerp(CAM.lens[0], CAM.lens[1], e);
  const row = curve(CAM.row, t);
  out.al = Math.atan((2 * row - 1) * (18 / out.lens) * (9 / 16));
  return out;
}

