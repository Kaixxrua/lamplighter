// the pour at t: each slot's fill (0 … 1), row by row (Fall's order)
const NCOL = T25.pour.cols.length;
export function pourAt(t) {
  const { t0, rows, cols, D } = T25.pour;
  return rows.flatMap((r) => cols.map((c) => smootherstep(t0 + r + c, t0 + r + c + D, t)));
}
export const POUR_END = T25.pour.t0 + Math.max(...T25.pour.rows) + Math.max(...T25.pour.cols) + T25.pour.D;
