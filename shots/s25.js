// a turn's e and curl at t (the board's, as s24 turns it)
const turnAt = ([a, b, B], t) => {
  const e = smootherstep(a, b, t);
  return { e, bend: B * Math.sin(2 * Math.PI * e) };
};
// The UI page's turn at t (s26 carries it on). It is a flip, not the others' even turn: this page is a grid
// of dark and light pictures, and every frame of it sweeping up through the picture is a frame with half the
// picture in transition (see Flashing), so it goes up through the picture in three frames. Its clock runs
// fast at first (u → 1 − (1 − u)^k, k = 2: twice the speed at the start, none at the end), so it is up
// quickly and comes down slowly; before it goes its fore-edge stirs (the peel: the curl alone, the tail
// corner most, fading as the page goes over).
export function turn25(t) {
  const [a, b, B, k] = T25.turn;
  const [p0, p1, P] = T25.peel;
  const e = smootherstep(0, 1, 1 - (1 - clamp((t - a) / (b - a))) ** k);
  return { e, bend: B * Math.sin(2 * Math.PI * e) + P * smoothstep(p0, p1, t) * (1 - smoothstep(0, 0.5, e)) };
}
// when that turn reaches e (it only rises)
export function turnTime(e) {
  let [lo, hi] = T25.turn;
  for (let i = 0; i < 40; i++) {
    const m = (lo + hi) / 2;
    if (turn25(m).e < e) lo = m;
    else hi = m;
  }
  return +hi.toFixed(3);
}

export async function setup(ctx) {
  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(30, 16 / 9, 0.1, 400);
  const K = BOOK.FLOOR;
  const lib = new Library({ floors: [K - 2, K + 2], near: 1, mid: 2, height: ctx.height });
  scene.add(lib.group);
  lib.setAll(() => ({ lit: 0, lime: 0, lamp: LOOK20.lamp }));
  const U = lib.uniforms;
  U.uFogD.value = 0.009;
  U.uFogCol.value.setRGB(0, 0, 0);
  U.uAmb.value.setRGB(0, 0, 0);

  // the captures, and what manifest.json says of them (in this language)
  const lang = ctx.lang;
  const entries = (await ctx.load.json('/assets/ui/manifest.json')).entries;
  const entry = (name) => entries.find((e) => e.name === name && e.lang === lang);
  const cards = entry('s25-ui').regions.cards;
  const load = (file) => ctx.load.texture(`/${file}`, { srgb: true, anisotropy: 8 });
  const [rec26, x24, paper, ink, ui25, full25] = await Promise.all([
    ...['s26-recommended', 's24-x', 's23-paper'].map((n) => load(`assets/ui/${lang}/${n}.png`)),
    loadInkCard(lang), // the tweet as s24 left it (c_ink.js)
    loadPage25(lang, cards), // the UI page, its works not in yet (s24.js)
    loadWindow(`/assets/ui/${lang}/s25-ui.png`, UI25.win), // … and with them in, as captured
  ]);
  const fall = new Fall({ base: ui25, full: full25, win: UI25.win, cards });
  // the leaves as s24 left them, s26's page under the UI page; the ones under the paper on the left are
  // never seen here (their prints are left out)
  const book = new Book({
    U,
    pages: [{ tex: rec26 }, { tex: ui25 }, { tex: x24 }, { tex: paper }, ...Array.from({ length: 6 }, () => ({ tex: null }))],
  });
  for (const l of book.leaves) l.hR -= SINK * BOOK.STEP;
  scene.add(book.group, book.world);
  book.setCover(Math.PI);
  const [p26, p25, p24, p23, ...under] = book.leaves;
  p26.hR -= DROP26 * BOOK.STEP;
  const mip = T24.develop[2];
  p26.u.uSharp.value = HOLD26; // s26 brings it sharp
  p25.mask(held25(lang), SIZE25, UI25.hold);
  p25.u.uSharp.value = UI25.hold;
  // the X board as s24 left it: sharp but its held boxes, the tweet in Chinese
  p24.mask(held24(lang), SIZE, mip);
  p24.u.uSharp.value = 0;
  // the paper as s23 left it: sharp but its held boxes, the figure printed whole, the bars down
  p23.mask(held23(lang), SIZE, mip);
  const cv = newFigureCanvas();
  drawFigure(cv, paper.image, 1, Array(10).fill(1));
  p23.inset(canvasTexture(cv, { srgb: true, mipmaps: true, anisotropy: 8 }), FIG.inset, SIZE, 1);
  p23.pose({ e: 1 });
  p23.u.uSpillK.value = 1;
  for (const l of under) {
    l.pose({ e: 1 });
    l.u.uSpillK.value = 1;
  }

  const F = book.F;
  const tgt = new THREE.Vector3();
  const pos = new THREE.Vector3();
  const k = LOOK20.page * BOOK_LOOK.glow;
  const pageL = BOOK_LOOK.paper.map((p) => p * k);

  return {
    scene,
    camera,
    clearColor: new THREE.Color(0, 0, 0),
    update(t, c) {
      // the X board lands (s24's turn); the UI page stirs and flips at the end
      const p4 = turnAt(T24.turn, T0 + t);
      p24.pose(p4);
      p24.u.uSpillK.value = smoothstep(0.2, 0.4, p4.e);
      p24.inset(ink.render(c.renderer, 1), INK.box, SIZE, 1, ink.sub);
      const p5 = turn25(t);
      p25.pose(p5);
      // it takes the page's light only once it is up past the camera (as the board did in s24)
      p25.u.uSpillK.value = smoothstep(0.2, 0.4, p5.e);
      p26.pose({ e: 0 });
      p26.u.uSpillK.value = 0;

      // the UI page comes sharp; its works pour in
      const [d0, d1, s0, s1] = T25.develop;
      p25.u.uSharp.value = lerp(s0, s1, smoothstep(d0, d1, t));
      p25.u.uTex.value = fall.render(c.renderer, pourAt(t), SEED);

      book.setLight({ page: pageL, edge: LOOK20.edge[1], logo: LOOK20.logo });

      // the camera
      const cm = camAt(t);
      F.toWorld(cm[3], cm[4], cm[5], tgt);
      F.toWorld(cm[0], cm[1], cm[2], pos);
      setLens(camera, track(LENS, t));
      aim(camera, pos, tgt);
      lib.update(camera);
      U.uTime.value = 86 + 4.0 + 3.0 + T0 + t;
    },
    post: (t) => ({ dof: { focus: focusDistance(camera, tgt), fstop: track(FSTOP, t) } }),
  };
}

