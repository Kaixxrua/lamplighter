// a monotone C1 curve through [t, v] keys (Fritsch–Carlson), leaving the first at slope m0 and coming
// to rest at the last
function curve(keys, m0 = 0) {
  const n = keys.length;
  const T = keys.map((k) => k[0]);
  const V = keys.map((k) => k[1]);
  const d = T.slice(1).map((t, i) => (V[i + 1] - V[i]) / (t - T[i]));
  const M = V.map((_, i) => {
    if (i === 0) return m0;
    if (i === n - 1 || d[i - 1] * d[i] <= 0) return 0;
    const h0 = T[i] - T[i - 1];
    const h1 = T[i + 1] - T[i];
    return (3 * (h0 + h1)) / ((2 * h1 + h0) / d[i - 1] + (h1 + 2 * h0) / d[i]);
  });
  return (t) => {
    if (t <= T[0]) return V[0] + m0 * (t - T[0]);
    if (t >= T[n - 1]) return V[n - 1];
    let i = 0;
    while (t > T[i + 1]) i++;
    const h = T[i + 1] - T[i];
    const u = (t - T[i]) / h;
    const [u2, u3] = [u * u, u * u * u];
    return (2 * u3 - 3 * u2 + 1) * V[i] + (u3 - 2 * u2 + u) * h * M[i]
      + (-2 * u3 + 3 * u2) * V[i + 1] + (u3 - u2) * h * M[i + 1];
  };
}

