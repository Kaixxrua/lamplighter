// the camera at t: where it is, the page's point it reads, which way it looks, lens, f-stop
export function camAt(t, out = { pos: new THREE.Vector3(), page: new THREE.Vector3(), dir: new THREE.Vector3() }) {
  out.pos.copy(P0).addScaledVector(RUN, run(t)).addScaledVector(off, bump(t));
  F.toWorld(look[0](t), look[1](t), look[2](t), out.page);
  const a = out.page.clone().sub(out.pos).normalize();
  const w = smootherstep(...CAM26.turn, t);
  const th = Math.acos(clamp(a.dot(D1), -1, 1));
  const s = Math.sin(th);
  if (s < 1e-6) out.dir.copy(D1);
  else out.dir.copy(a).multiplyScalar(Math.sin((1 - w) * th) / s).addScaledVector(D1, Math.sin(w * th) / s);
  out.lens = track(CAM26.lens, t);
  out.fstop = track(CAM26.fstop, t);
  return out;
}
